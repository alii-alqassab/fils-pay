import { randomUUID } from "node:crypto";
import type { Pool } from "pg";
import { ZERO_FILS, addFils, calculateRefundFee, compareFils, subtractFils, toFils, type Fils } from "@filspay/money";
import { enqueueEvent } from "@filspay/events";
import { withTransaction } from "../db/withTransaction.js";
import type { AcquirerSimulator } from "../acquirer/types.js";
import { claimIdempotencyKey, completeIdempotencyKey, failIdempotencyKey, hashRequest } from "./idempotency.js";
import { recordTransactionEvent } from "../transactions/events.js";
import { nextStatusAfterRefund } from "./refundState.js";
import { validateRefundRequest } from "./refundValidation.js";
import { ConflictError, UnprocessableEntityError } from "../lib/errors.js";

const ENDPOINT = "refunds.create";
// Matches the column default set in db/migrations/0070_refund_reason_default.sql.
const REFUND_REASON_DEFAULT = "unspecified";

export interface ProcessRefundInput {
  transactionId: string;
  merchantId: string;
  amountFils?: Fils;
  idempotencyKey: string;
  actor: { type: "merchant_session" | "merchant_api_key"; id: string };
  reason?: string;
}

export interface ProcessRefundResult {
  statusCode: number;
  body: unknown;
}

interface RefundTransactionRow {
  id: string;
  merchant_id: string;
  status: string;
  amount_fils: string | number;
  captured_fils: string | number;
  refunded_fils: string | number;
  acquirer_reference: string;
}

/** Refund business logic: validate, call the acquirer, then journal the reversal. */
export async function processRefund(
  pool: Pool,
  acquirer: AcquirerSimulator,
  input: ProcessRefundInput,
): Promise<ProcessRefundResult> {
  const requestHash = hashRequest({
    transactionId: input.transactionId,
    amountFils: input.amountFils ?? null,
    reason: input.reason ?? null,
  });

  // Keep the transaction row lock from capacity validation through the
  // acquirer call and journal update. Different idempotency keys otherwise
  // could both validate against the same refunded_fils value and exceed the
  // captured amount. This follows captureTransaction's row-locking pattern.
  return withTransaction(pool, async (client) => {
    const claim = await claimIdempotencyKey(client, {
      merchantId: input.merchantId,
      endpoint: ENDPOINT,
      key: input.idempotencyKey,
      requestHash,
    });

    if (claim.outcome === "conflict_hash_mismatch") {
      throw new UnprocessableEntityError("idempotency_key_reused");
    }
    if (claim.outcome === "conflict_in_progress") {
      throw new ConflictError("request_in_progress");
    }
    if (claim.outcome === "replay") {
      return { statusCode: claim.row.responseStatusCode ?? 200, body: claim.row.responseBody };
    }

    const txnResult = await client.query<RefundTransactionRow>(
      `SELECT id, merchant_id, status, amount_fils, captured_fils, refunded_fils, acquirer_reference
         FROM transactions
        WHERE id = $1
        FOR UPDATE`,
      [input.transactionId],
    );
    const txn = txnResult.rows[0];
    if (!txn) {
      const body = { error: "transaction_not_found" };
      await completeIdempotencyKey(client, claim.row.id, { statusCode: 404, body });
      return { statusCode: 404, body };
    }

    // processRefund is callable without initiateMerchantRefund: never journal
    // a reversal against a transaction another merchant owns.
    if (txn.merchant_id !== input.merchantId) {
      const body = { error: "transaction_not_found" };
      await completeIdempotencyKey(client, claim.row.id, { statusCode: 404, body });
      return { statusCode: 404, body };
    }

    // A refund lowers what the merchant is owed. Settlement payouts decide "can I pay this?" under the
    // same merchant row lock, so a refund and a payout of one merchant can no longer both spend the
    // same balance (lock order: transaction, then merchant, matching settlement's batch, then merchant).
    await client.query(`SELECT 1 FROM merchants WHERE id = $1 FOR NO KEY UPDATE`, [txn.merchant_id]);

    const amountAuthorized = toFils(Number(txn.amount_fils));
    const capturedFils = toFils(Number(txn.captured_fils));
    const refundedFils = toFils(Number(txn.refunded_fils));

    const refundableFils = subtractFils(capturedFils, refundedFils);

    const validation = validateRefundRequest(
      {
        id: txn.id,
        merchantId: txn.merchant_id,
        status: txn.status,
        capturedFils,
        refundableFils,
      },
      input.amountFils,
    );

    if (!validation.ok) {
      const statusCode = validation.code === "transaction_not_refundable" ? 409 : 422;
      await completeIdempotencyKey(client, claim.row.id, { statusCode, body: validation });
      return { statusCode, body: validation };
    }

    // The net fee actually retained for this transaction, read from the
    // ledger rather than recomputed from the merchant's current mdr_bps.
    // Negotiated discounts are debit legs against platform_fee_revenue, so
    // counting credits alone would reverse fee the merchant never paid.
    const feeResult = await client.query<{ fee_fils: string }>(
      `SELECT COALESCE(SUM(CASE WHEN direction = 'credit' THEN amount_fils ELSE -amount_fils END), 0)::text AS fee_fils
         FROM ledger_entries
        WHERE transaction_id = $1
          AND account_id = 'platform_fee_revenue'
          AND description IN ('capture: MDR fee', 'capture: negotiated discount adjustment')
          AND direction IN ('credit', 'debit')`,
      [txn.id],
    );
    const feeRow = feeResult.rows[0];
    if (!feeRow) {
      throw new Error("processRefund: fee aggregate returned no row");
    }
    const netFeeCharged = toFils(Number(feeRow.fee_fils), { allowNegative: true });
    const feeChargedFils = compareFils(netFeeCharged, ZERO_FILS) > 0 ? netFeeCharged : ZERO_FILS;
    const previousFeeReversals = await client.query<{ fee_reversed_fils: string }>(
      `SELECT COALESCE(SUM(fee_reversed_fils), 0)::text AS fee_reversed_fils
         FROM refunds
        WHERE transaction_id = $1 AND status = 'succeeded'`,
      [txn.id],
    );
    const previousFeeReversedFils = toFils(Number(previousFeeReversals.rows[0]?.fee_reversed_fils ?? "0"));

    // Deliberately perform the external request while holding the transaction
    // row lock. The lock serializes other refunds for this transaction until
    // the successful result is recorded, so their subsequent capacity check
    // observes the updated refunded_fils value.
    const acquirerResult = await acquirer.refund({
      acquirerReference: txn.acquirer_reference,
      amountFils: validation.amountFils,
      // The database claim may roll back if the process crashes after the
      // acquirer accepted the refund but before the journal commits. Derive
      // the external key from the caller's durable idempotency scope so a
      // retry uses the same acquirer key even if the claim row is recreated.
      idempotencyKey: `refund:${hashRequest({
        merchantId: input.merchantId,
        endpoint: ENDPOINT,
        key: input.idempotencyKey,
        requestHash,
      })}`,
    });

    if (acquirerResult.outcome === "declined") {
      const body = { error: "refund_declined" };
      await completeIdempotencyKey(client, claim.row.id, { statusCode: 402, body });
      return { statusCode: 402, body };
    }
    if (acquirerResult.outcome === "error") {
      const body = { error: "acquirer_unavailable" };
      await failIdempotencyKey(client, claim.row.id, { statusCode: 502, body });
      return { statusCode: 502, body };
    }

    const newRefundedTotal = addFils(refundedFils, validation.amountFils);
    const newStatus = nextStatusAfterRefund({
      amountFils: amountAuthorized,
      capturedFils,
      refundedTotalFils: newRefundedTotal,
    });
    // Compute the cumulative fee reversal, then post only the difference
    // from prior successful refunds. Rounding each partial independently can
    // leave a one-fils remainder (or exceed the original fee) when the
    // transaction is fully refunded.
    const cumulativeFeeReversedFils = calculateRefundFee(
      capturedFils,
      feeChargedFils,
      newRefundedTotal,
    );
    // Older refunds may already have reversed more than the newly computed
    // discounted-fee total. Never post another reversal in that case; the
    // next refund must not deepen an existing over-reversal.
    const feeReversedFils =
      compareFils(previousFeeReversedFils, cumulativeFeeReversedFils) >= 0
        ? ZERO_FILS
        : subtractFils(cumulativeFeeReversedFils, previousFeeReversedFils);

    const refundResult = await client.query<{ id: string; occurred_at: Date }>(
      `INSERT INTO refunds
         (transaction_id, merchant_id, amount_fils, fee_reversed_fils, status,
          acquirer_reference, reason, created_by_type, created_by_id)
       VALUES ($1, $2, $3, $4, 'succeeded', $5, $6, $7, $8)
       RETURNING id, occurred_at`,
      [
        txn.id,
        txn.merchant_id,
        validation.amountFils,
        feeReversedFils,
        acquirerResult.acquirerReference,
        // Migration 0070 makes reason NOT NULL (default 'unspecified'); an
        // explicit NULL bypasses the column default, so apply it here.
        input.reason?.trim() || REFUND_REASON_DEFAULT,
        input.actor.type,
        input.actor.id,
      ],
    );
    const refund = refundResult.rows[0];
    if (!refund) {
      throw new Error("processRefund: insert into refunds returned no row");
    }

    await client.query(`UPDATE transactions SET refunded_fils = $2, status = $3 WHERE id = $1`, [
      txn.id,
      newRefundedTotal,
      newStatus,
    ]);

    // Double-entry reversal, mirroring capture's legs with the directions
    // swapped. ledger_entries has CHECK (amount_fils > 0), so a reversal
    // flips direction and never the sign.
    const entryGroupId = randomUUID();
    await client.query(
      `INSERT INTO ledger_entries
         (entry_group_id, merchant_id, transaction_id, account_id, direction, amount_fils, occurred_at, description)
       VALUES
         ($1, $2, $3, 'merchant_payable',     'debit',  $4, now(), 'refund: gross'),
         ($1, $2, $3, 'card_scheme_clearing', 'credit', $4, now(), 'refund: gross')`,
      [entryGroupId, txn.merchant_id, txn.id, validation.amountFils],
    );
    if (compareFils(feeReversedFils, ZERO_FILS) > 0) {
      await client.query(
        `INSERT INTO ledger_entries
           (entry_group_id, merchant_id, transaction_id, account_id, direction, amount_fils, occurred_at, description)
         VALUES
           ($1, $2, $3, 'platform_fee_revenue', 'debit',  $4, now(), 'refund: MDR fee reversal'),
           ($1, $2, $3, 'merchant_payable',     'credit', $4, now(), 'refund: MDR fee reversal')`,
        [entryGroupId, txn.merchant_id, txn.id, feeReversedFils],
      );
    }

    // The timeline records what this refund did to the captured amount, so
    // it stays readable regardless of what the status column ends up
    // saying: everything captured has now gone back, or only part of it has.
    const eventType = compareFils(newRefundedTotal, capturedFils) >= 0 ? "refunded" : "refund_partial";

    await recordTransactionEvent(client, {
      transactionId: txn.id,
      eventType,
      amountFils: toFils(-validation.amountFils, { allowNegative: true }),
      actor: input.actor,
      metadata: {
        refundId: refund.id,
        feeReversedFils,
        acquirerReference: acquirerResult.acquirerReference,
      },
    });

    await enqueueEvent(client, {
      eventType: "refund.succeeded",
      aggregateType: "transaction",
      aggregateId: txn.id,
      payload: {
        merchantId: txn.merchant_id,
        refundId: refund.id,
        amountFils: validation.amountFils,
        feeReversedFils,
        refundedTotalFils: newRefundedTotal,
        newStatus,
      },
    });

    const body = {
      id: refund.id,
      transactionId: txn.id,
      merchantId: txn.merchant_id,
      amountFils: validation.amountFils,
      feeReversedFils,
      status: "succeeded",
      transactionStatus: newStatus,
      refundedTotalFils: newRefundedTotal,
      acquirerReference: acquirerResult.acquirerReference,
      occurredAt: refund.occurred_at.toISOString(),
    };
    await completeIdempotencyKey(client, claim.row.id, {
      statusCode: 200,
      body,
      resourceId: refund.id,
    });
    return { statusCode: 200, body };
  });
}
